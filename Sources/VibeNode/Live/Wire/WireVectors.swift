/// The web client's validators and vectors, written from `WireSchema` and `VibeNode`'s own encoders (the live plan's
/// LW-D10 and E1, lane E's file): `files()` is `WebApp/wire/validators.js` and `WebApp/wire/vectors.json`, as
/// `vibeswitcher wire-vectors --out DIR` writes them and `WireVectorsTests` holds the checked-in ones to.
///
/// The vectors are the live wire contract's frames, by the names its §11 gives them and §8's (`draft.acked`,
/// `draft.refused`, `answer.from-a-page`), plus a few more a client's tests want. A card, a lead and every `NodeWire`
/// message are their encoders' output; a session, the node, the snapshot and delta envelopes and the chat are written
/// here as the contract gives them until the task that makes their encoder lands (B1, B2, B4), when they're built from
/// it. Where an encoder writes other than the contract's example (a project id is a hash of the root; a question at
/// version 2 has a revision note; a hello's absent host field isn't written as null), the vector is the encoder's.
public enum WireVectors {
    /// One frame, and the kind `WireSchema.check` and `validate` check it as.
    public struct Frame: Equatable, Sendable {
        public var kind: String
        public var value: NodeWire.Value
    }

    /// A named vector: one frame, or the frames of an exchange in order (written as a list).
    public struct Vector: Equatable, Sendable {
        public var name: String
        public var frames: [Frame]
    }

    // MARK: The files

    /// `validators.js` and `vectors.json`, by name.
    public static func files() -> [String: Data] {
        ["validators.js": Data(validators.utf8), "vectors.json": Data(vectors.utf8)]
    }

    /// `{name: frame}`, the names sorted, one vector a line; an exchange's frames as a list.
    static var vectors: String {
        let lines = all.sorted { precedes($0.name, $1.name) }.map { vector in
            let body = vector.frames.count == 1 ? json(vector.frames[0].value) : json(.array(vector.frames.map(\.value)))
            return "  \(quote(vector.name)): \(body)"
        }
        return "{\n" + lines.joined(separator: ",\n") + "\n}\n"
    }

    static var validators: String {
        let shapes = WireSchema.shapes.keys.sorted(by: precedes).map { "  \(quote($0)): \(json(value(WireSchema.shapes[$0]!)))" }
        let collections = json(.object(WireSchema.collections.mapValues(NodeWire.Value.string)))
        return """
            // Generated by `vibeswitcher wire-vectors --out WebApp/wire` from VibeNode's WireSchema (Sources/VibeNode/Live/Wire):
            // don't edit it, regenerate it. WireVectorsTests fails while it is stale. No dependency, no build step: an ES module
            // the page and Node's tests import as it is.
            //
            // validate(kind, value): the first field that fails, as "<path>: <why>" ("entries[0].value.since: expected a
            // date"), or null. kind is a shape's name (an entity: "node", "session", "lead", "card", "chat.item"; a message:
            // "request", "reply", "hello", "bye", "snapshot", "delta", "<kind>.args", "<kind>.result", ...), or "frame" (any
            // message, told apart by its fields), "reply.<request kind>" (its result checked when the schema has one) or
            // "delta.<collection>" (its changes checked as that collection's entities). A request's args are checked by its
            // kind, a snapshot's entries by its collection. Rule 3: a field the schema doesn't name passes, as does a word or a
            // union's case it doesn't know.

            export const shapes = {
            \(shapes.joined(separator: ",\n"))
            };

            export const collections = \(collections);

            const DATE = /\(WireSchema.datePattern)/;
            const has = (object, key) => Object.prototype.hasOwnProperty.call(object, key) && object[key] !== undefined;
            const isObject = (value) => value !== null && typeof value === "object" && !Array.isArray(value);
            const at = (path, key) => (path === "" ? key : `${path}.${key}`);
            const label = (path, root) => (path === "" ? root : path);
            const order = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

            /// The kind "frame" checks a message as: a reply has `re`, a request `id`, an event its `kind`.
            export function frameKind(value) {
              if (!isObject(value)) return "event";
              if (has(value, "re")) return "reply";
              if (has(value, "id")) return "request";
              return ["hello", "bye", "snapshot", "delta"].includes(value.kind) ? value.kind : "event";
            }

            export function validate(kind, value) {
              if (kind === "frame") return validate(frameKind(value), value);
              if (kind === "request") {
                const failure = checkShape(value, "request", "", kind);
                if (failure !== null) return failure;
                const args = `${value.kind}.args`;
                return has(value, "args") && has(shapes, args) ? checkType(value.args, { shape: args }, "args", kind) : null;
              }
              if (kind.startsWith("reply.")) {
                const failure = checkShape(value, "reply", "", kind);
                if (failure !== null) return failure;
                const result = `${kind.slice("reply.".length)}.result`;
                return value.ok === true && has(value, "result") && has(shapes, result)
                  ? checkType(value.result, { shape: result }, "result", kind)
                  : null;
              }
              if (kind === "snapshot" || kind.startsWith("delta.")) {
                const envelope = kind === "snapshot" ? "snapshot" : "delta";
                const failure = checkShape(value, envelope, "", kind);
                if (failure !== null) return failure;
                const collection = kind === "snapshot" ? value.collection : kind.slice("delta.".length);
                if (!has(collections, collection)) return null;
                const list = envelope === "snapshot" ? "entries" : "changes";
                const entries = Array.isArray(value[list]) ? value[list] : [];
                for (let index = 0; index < entries.length; index++) {
                  const body = entries[index].value;
                  if (body === null || body === undefined) continue;
                  const failed = checkType(body, { shape: collections[collection] }, `${list}[${index}].value`, kind);
                  if (failed !== null) return failed;
                }
                return null;
              }
              if (!has(shapes, kind)) return `${kind}: no such kind`;
              return checkShape(value, kind, "", kind);
            }

            function checkType(value, type, path, root) {
              switch (type) {
                case "string":
                  return typeof value === "string" ? null : `${label(path, root)}: expected a string`;
                case "int":
                  return Number.isInteger(value) ? null : `${label(path, root)}: expected an integer`;
                case "bool":
                  return typeof value === "boolean" ? null : `${label(path, root)}: expected true or false`;
                case "date":
                  return typeof value === "string" && DATE.test(value) ? null : `${label(path, root)}: expected a date`;
                case "any":
                  return null;
              }
              if (has(type, "nullable")) return value === null ? null : checkType(value, type.nullable, path, root);
              if (has(type, "words")) return typeof value === "string" ? null : `${label(path, root)}: expected a string`;
              if (has(type, "list")) {
                if (!Array.isArray(value)) return `${label(path, root)}: expected a list`;
                for (let index = 0; index < value.length; index++) {
                  const failure = checkType(value[index], type.list, `${path}[${index}]`, root);
                  if (failure !== null) return failure;
                }
                return null;
              }
              if (has(type, "map")) {
                if (!isObject(value)) return `${label(path, root)}: expected an object`;
                for (const key of Object.keys(value).sort(order)) {
                  const failure = checkType(value[key], type.map, at(path, key), root);
                  if (failure !== null) return failure;
                }
                return null;
              }
              return checkShape(value, type.shape, path, root);
            }

            function checkShape(value, name, path, root) {
              const shape = shapes[name];
              if (shape === undefined) return `${label(path, root)}: no shape ${name}`;
              if (!isObject(value)) return `${label(path, root)}: expected an object`;
              if (has(shape, "union")) {
                const tag = shape.union.tag;
                if (!has(value, tag)) return `${at(path, tag)}: missing`;
                if (typeof value[tag] !== "string") return `${at(path, tag)}: expected a string`;
                return has(shape.union.cases, value[tag]) ? checkShape(value, shape.union.cases[value[tag]], path, root) : null;
              }
              for (const field of shape.fields) {
                if (!has(value, field.name)) {
                  if (field.optional) continue;
                  return `${at(path, field.name)}: missing`;
                }
                const failure = checkType(value[field.name], field.type, at(path, field.name), root);
                if (failure !== null) return failure;
              }
              return null;
            }

            """
    }

    /// A shape as `validators.js`'s table holds it.
    private static func value(_ shape: WireSchema.Shape) -> NodeWire.Value {
        var fields: [String: NodeWire.Value] = ["from": .string(shape.from)]
        if let union = shape.union {
            fields["union"] = .object(["tag": .string(union.tag), "cases": .object(union.cases.mapValues(NodeWire.Value.string))])
        } else {
            fields["fields"] = .array(shape.fields.map { field in
                var entry: [String: NodeWire.Value] = ["name": .string(field.name), "type": value(field.type)]
                if field.optional { entry["optional"] = .bool(true) }
                if let pending = field.pending { entry["pending"] = .string(pending) }
                return .object(entry)
            })
        }
        return .object(fields)
    }

    private static func value(_ type: WireSchema.Kind) -> NodeWire.Value {
        switch type {
        case .string: return .string("string")
        case .int: return .string("int")
        case .bool: return .string("bool")
        case .date: return .string("date")
        case .any: return .string("any")
        case .words(let words): return .object(["words": .array(words.map(NodeWire.Value.string))])
        case .list(let inner): return .object(["list": value(inner)])
        case .map(let inner): return .object(["map": value(inner)])
        case .shape(let name): return .object(["shape": .string(name)])
        case .nullable(let inner): return .object(["nullable": value(inner)])
        }
    }

    // MARK: JSON, the same bytes on every system

    /// Whether `a` sorts before `b`: by UTF-8 bytes (JavaScript's sort agrees on every key the wire has).
    static func precedes(_ a: String, _ b: String) -> Bool { a.utf8.lexicographicallyPrecedes(b.utf8) }

    /// `value` as compact JSON, its keys sorted: written here, not by JSONEncoder, whose spacing and escapes aren't the
    /// same on every system.
    static func json(_ value: NodeWire.Value) -> String {
        switch value {
        case .null: return "null"
        case .bool(let flag): return flag ? "true" : "false"
        case .int(let number): return String(number)
        case .double(let number): return number.isFinite ? "\(number)" : "null"
        case .string(let text): return quote(text)
        case .array(let items): return "[" + items.map(json).joined(separator: ",") + "]"
        case .object(let fields):
            return "{" + fields.keys.sorted(by: precedes).map { quote($0) + ":" + json(fields[$0]!) }.joined(separator: ",") + "}"
        }
    }

    static func quote(_ text: String) -> String {
        var out = "\""
        for scalar in text.unicodeScalars {
            switch scalar {
            case "\"": out += "\\\""
            case "\\": out += "\\\\"
            case "\n": out += "\\n"
            case "\r": out += "\\r"
            case "\t": out += "\\t"
            case _ where scalar.value < 0x20 || scalar.value == 0x2028 || scalar.value == 0x2029:
                out += "\\u" + String(repeating: "0", count: 4 - String(scalar.value, radix: 16).count) + String(scalar.value, radix: 16)
            default: out.unicodeScalars.append(scalar)
            }
        }
        return out + "\""
    }

