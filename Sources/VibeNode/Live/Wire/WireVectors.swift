    static func date(_ text: String) -> Date { NodeWire.date(text) ?? Date(timeIntervalSince1970: 0) }

    /// What an encodable message writes, as a value.
    static func encoded<T: Encodable>(_ message: T) -> NodeWire.Value {
        NodeWire.decode(NodeWire.Value.self, NodeWire.line(message).dropLast()) ?? .null
    }

    static func frame(_ kind: String, _ value: NodeWire.Value) -> Frame { Frame(kind: kind, value: value) }
    static func request(_ message: NodeWire.Request) -> Frame { frame("request", encoded(message)) }
    static func reply(_ message: NodeWire.Reply) -> Frame { frame("reply", encoded(message)) }
    /// A reply checked as `kind` (`reply.subscribe`: its result as `subscribe.result`).
    static func reply(_ kind: String, _ message: NodeWire.Reply) -> Frame { frame(kind, encoded(message)) }

    static func subscribe(_ id: String, _ sub: String, _ collection: String, extra: [String: NodeWire.Value] = [:]) -> Frame {
        request(.init(id: id, kind: "subscribe",
                      args: ["sub": .string(sub), "collection": .string(collection)].merging(extra) { $1 }))
    }

    static func snapshot(_ sub: String, _ collection: String, epoch: String = WireVectors.epoch, seq: Int,
                         entries: [(String, NodeWire.Value)]) -> Frame {
        frame("snapshot", .object(["v": .int(NodeWire.version), "kind": .string("snapshot"), "sub": .string(sub),
                                   "collection": .string(collection), "epoch": .string(epoch), "seq": .int(seq),
                                   "entries": .array(entries.map { .object(["id": .string($0.0), "value": $0.1]) })]))
    }

    static func delta(_ sub: String, _ collection: String, prev: Int, seq: Int, at: String, changes: [(String, NodeWire.Value)]) -> Frame {
        frame("delta.\(collection)", .object([
            "v": .int(NodeWire.version), "kind": .string("delta"), "sub": .string(sub), "prev": .int(prev), "seq": .int(seq),
            "at": .string(at), "changes": .array(changes.map { .object(["id": .string($0.0), "value": $0.1]) })]))
    }

