import Foundation

/// The request kinds as docs/guide/v2-architecture.md tables them, made from the table the server runs on (`KindSpec`)
/// and its views (`Requests.recorded`, `carded`, `RequestArguments`): the page never says what the code doesn't. `vibeswitcher kinds-doc --write FILE` puts it between the page's markers;
/// ArchitectureDocLintTests fails while the page's table isn't this one.
public enum KindsTable {
    public static let begin = "<!-- kinds-table: generated by `vibeswitcher kinds-doc --write docs/guide/v2-architecture.md`; don't edit -->"
    public static let end = "<!-- kinds-table end -->"

    static func voice(_ voice: NodeWire.Voice) -> String {
        switch voice {
        case .anyone: return "anyone of the uid"
        case .user: return "the user's terminal"
        case .leadToolServer: return "a lead's tool server"
        case .webRead: return "the user's terminal, or a page that reads"
        case .webDraft: return "a page that drafts"
        case .webTerminal: return "a page's terminal"
        }
    }

    static func handler(_ spec: KindSpec) -> String {
        switch spec.servedBy {
        case .hub: return "the live hub"
        case .terminalRelay: return "the terminal relay"
        case .requests:
            switch spec.sender {
            case .leadToolServer: return "`questionPost`"
            case .webDraft: return "`draft`"
            default: return "`Requests.act`"
            }
        }
    }

    /// Its typed arguments and result (`WireKind`, by the type's name), or none.
    static func wire(_ spec: KindSpec) -> String {
        switch spec.wire {
        case .typed(let type): return "`WireKinds.\(String(describing: type))`"
        case .page: return "the page's (WireSchema)"
        case .notYet: return "not yet"
        }
    }

    /// A recorded kind's retry (`Requests.RetryRule`): what it is given, and whether one with no outcome is done again.
    static func retry(_ spec: KindSpec) -> String {
        guard let recorded = spec.recorded else { return "" }
        return (recorded.keepsResult ? "its result" : "done, no result") + (recorded.rerun ? "; done again" : "")
    }

    /// Whether an acting page may send a user's kind (`KindSpec.page`).
    static func page(_ spec: KindSpec) -> String {
        switch spec.page {
        case .bySender: return ""
        case .acts: return "yes"
        case .terminalOnly: return "the terminal's alone"
        }
    }

    /// The table, one row per kind (`KindSpec.all`), sorted.
    public static func markdown() -> String {
        var lines = ["| Kind | Who may send it | Changes state | Recorded first | Card code | Handled by | Arguments (state changes) | Typed "
                     + "| A retry | In approve's batch | From an acting page |",
                     "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
        let taken = Set(NodeWire.taken)
        for spec in KindSpec.all.sorted(by: { $0.name < $1.name }) {
            let kind = spec.name
            let yes = { (flag: Bool) in flag ? "yes" : "" }
            let arguments = RequestArguments.taken[kind].map { $0.isEmpty ? "none" : $0.sorted().map { "`\($0)`" }.joined(separator: ", ") } ?? ""
            let on = taken.contains(kind) ? "" : " (a page only)"
            lines.append("| `\(kind)` | \(voice(spec.sender))\(on) | \(yes(spec.changesState)) | \(yes(Requests.recorded.contains(kind))) "
                         + "| \(yes(Requests.carded.contains(kind))) | \(handler(spec)) | \(arguments) | \(wire(spec)) | \(retry(spec)) "
                         + "| \(yes(spec.recorded?.batch == true)) | \(page(spec)) |")
        }
        return lines.joined(separator: "\n")
    }

    /// `text` with the table between its markers made again; nil when it has no pair of markers.
    public static func replacing(in text: String) -> String? {
        guard let start = text.range(of: begin), let stop = text.range(of: end, range: start.upperBound..<text.endIndex) else { return nil }
        return String(text[..<start.upperBound]) + "\n" + markdown() + "\n" + String(text[stop.lowerBound...])
    }
}
