import Foundation

/// The request kinds as docs/guide/v2-architecture.md tables them, made from the lists the server runs on
/// (`NodeWire.kinds`, `changesState`, `taken`, `Requests.recorded`, `carded`, `RequestArguments`, `LiveHub.kinds`): the
/// page never says what the code doesn't. `vibeswitcher kinds-doc --write FILE` puts it between the page's markers;
/// ArchitectureDocLintTests fails while the page's table isn't this one.
public enum KindsTable {
    public static let begin = "<!-- kinds-table: generated by `vibeswitcher kinds-doc --write docs/guide/v2-architecture.md`; don't edit -->"
    public static let end = "<!-- kinds-table end -->"

    static func voice(_ voice: NodeWire.Voice) -> String {
        switch voice {
        case .anyone: return "anyone of the uid"
        case .user: return "the user's terminal"
        case .leadToolServer: return "a lead's tool server"
        case .webRead: return "the user's terminal, or a page that reads"
        case .webDraft: return "a page that drafts"
        case .webTerminal: return "a page's terminal"
        }
    }

    static func handler(_ kind: String, _ voice: NodeWire.Voice) -> String {
        if LiveHub.kinds.contains(kind) { return "the live hub" }
        switch voice {
        case .leadToolServer: return "`questionPost`"
        case .webDraft: return "`draft`"
        case .webTerminal: return "the terminal relay"
        default: return "`Requests.act`"
        }
    }

    /// The table, one row per kind, sorted.
    public static func markdown() -> String {
        var lines = ["| Kind | Who may send it | Changes state | Recorded first | Card code | Handled by | Arguments (state changes) |",
                     "| --- | --- | --- | --- | --- | --- | --- |"]
        let taken = Set(NodeWire.taken)
        for (kind, needs) in NodeWire.kinds.sorted(by: { $0.key < $1.key }) {
            let yes = { (flag: Bool) in flag ? "yes" : "" }
            let arguments = RequestArguments.taken[kind].map { $0.isEmpty ? "none" : $0.sorted().map { "`\($0)`" }.joined(separator: ", ") } ?? ""
            let on = taken.contains(kind) ? "" : " (a page only)"
            lines.append("| `\(kind)` | \(voice(needs))\(on) | \(yes(NodeWire.changesState(kind))) | \(yes(Requests.recorded.contains(kind))) "
                         + "| \(yes(Requests.carded.contains(kind))) | \(handler(kind, needs)) | \(arguments) |")
        }
        return lines.joined(separator: "\n")
    }

    /// `text` with the table between its markers made again; nil when it has no pair of markers.
    public static func replacing(in text: String) -> String? {
        guard let start = text.range(of: begin), let stop = text.range(of: end, range: start.upperBound..<text.endIndex) else { return nil }
        return String(text[..<start.upperBound]) + "\n" + markdown() + "\n" + String(text[stop.lowerBound...])
    }
}
