export const TABLES = { en: EN, es: ES };

// The first of the browser's languages the table has, by its primary subtag ("es-ES" is "es"); else English.
export function pickLanguage(languages = [], wanted = null) {
  for (const tag of [wanted, ...languages]) {
    const code = String(tag || '').toLowerCase().split('-')[0];
    if (TABLES[code]) return code;
  }
  return 'en';
}

const env = globalThis;
let language = pickLanguage(env.navigator?.languages || [env.navigator?.language], env.location ? new URLSearchParams(env.location.search).get('lang') : null);

export const lang = () => language;
// For the tests.
export function setLanguage(code) { language = TABLES[code] ? code : 'en'; }

export function t(key, values = {}) {
  let word = TABLES[language][key] ?? EN[key] ?? key;
  if (typeof word === 'object') word = values.n === 1 ? word.one : word.other;
  return word.replace(/\{(\w+)\}/g, (all, name) => (values[name] ?? all));
}

// The node's own words for a task (BoardValue: its state in the Mac's Team words, and the few fixed lines under it),
