// "a, b and c" / "a, b y c".
export function listed(items) {
  if (items.length < 2) return items.join('');
  return `${items.slice(0, -1).join(', ')} ${language === 'es' ? 'y' : 'and'} ${items[items.length - 1]}`;
}
